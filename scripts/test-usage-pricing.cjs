const cache = new Map();
function load(file) {
  file = path.resolve(file);
  if (cache.has(file)) return cache.get(file);
  const exports = {}; cache.set(file, exports);
  const source = ts.transpileModule(fs.readFileSync(file, "utf8"), { compilerOptions: { target: 9, module: 1 } }).outputText;
  new Function("require", "exports", source)(name => name.endsWith(".mjs") ? require(path.resolve(path.dirname(file), name)) : name.startsWith(".") ? load(path.resolve(path.dirname(file), name + ".ts")) : require(name), exports);
  return exports;
}
